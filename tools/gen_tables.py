"""Bake the trig tables into source.

These are *data*, not code that runs at load time, and that is the whole point.
ECMAScript does not pin Math.sin or Math.atan to any precision -- the spec
calls the result "implementation-approximated", so two JS engines are permitted
to disagree in the last bit. In a lockstep RTS a last-bit disagreement is a
desync twenty minutes later, in a battle, with no way to reproduce it. So the
tables are computed once, here, by CPython, and checked in as integer literals.
After that no floating-point transcendental is ever evaluated at runtime on any
machine, and every client turns its units through exactly the same angles.

Re-run only if ANGLE_TURN or SCALE change, and re-anchor the baseline after.
"""
import math, pathlib

SCALE = 4096        # fixed-point denominator: 1 unit = 1/4096 m
ANGLE_TURN = 1024   # binary angle units in one full turn
QUARTER = ANGLE_TURN // 4
ATAN_STEPS = 256    # table resolution for ratios in [0, 1]


def rows(vals, per=16):
    out = []
    for i in range(0, len(vals), per):
        out.append("  " + ", ".join(str(v) for v in vals[i:i + per]) + ",")
    return "\n".join(out).rstrip(",")


# Quarter wave, 0..QUARTER inclusive. The endpoint is needed so that cos can be
# read as sin shifted by a quarter turn without a special case at the seam.
sin_vals = [round(math.sin(2 * math.pi * i / ANGLE_TURN) * SCALE)
            for i in range(QUARTER + 1)]
assert sin_vals[0] == 0 and sin_vals[QUARTER] == SCALE

# atan(i/ATAN_STEPS) in binary angle units, for ratios 0..1 -- the first
# half-octant. Everything else is reached by reflection in atan2 below.
atan_vals = [round(math.atan(i / ATAN_STEPS) / (2 * math.pi) * ANGLE_TURN)
             for i in range(ATAN_STEPS + 1)]
assert atan_vals[0] == 0 and atan_vals[ATAN_STEPS] == ANGLE_TURN // 8

out = pathlib.Path(__file__).resolve().parent.parent / "sim" / "tables.ts"
out.write_text(f"""// GENERATED by tools/gen_tables.py -- do not hand-edit.
//
// Baked rather than computed at load time because ECMAScript does not pin
// Math.sin or Math.atan to a precision: two engines may legally differ in the
// last bit, and under lockstep a last-bit difference is a desync. Regenerate
// with `python tools/gen_tables.py` and re-anchor the baseline.

/** Binary angle units in one full turn. A unit is 360/1024 = 0.352 degrees. */
export const ANGLE_TURN = {ANGLE_TURN};
export const QUARTER = {QUARTER};
export const ATAN_STEPS = {ATAN_STEPS};

/** sin(2*PI*i/{ANGLE_TURN}) * {SCALE}, i = 0..{QUARTER}. */
export const SIN_QUARTER: readonly number[] = [
{rows(sin_vals)},
];

/** atan(i/{ATAN_STEPS}) in binary angle units, i = 0..{ATAN_STEPS}. */
export const ATAN_TABLE: readonly number[] = [
{rows(atan_vals)},
];
""")
print(f"wrote {out}: {len(sin_vals)} sin entries, {len(atan_vals)} atan entries")
